// Converts the source artwork in assets-source/ into web-sized WebP files in
// public/assets/. Source PNGs stay out of public/ so they are never shipped.
// Run with: npm run images
import { mkdir, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const ROOT = path.resolve(import.meta.dirname, '..')
const SOURCE = path.join(ROOT, 'assets-source')
const OUT = path.join(ROOT, 'public/assets')

// Widest the asset is ever displayed at, doubled for retina.
const MAX_WIDTH = {
  images: 1600,
  icons: 128,
}

const manifest = {}

for (const kind of Object.keys(MAX_WIDTH)) {
  const dir = path.join(SOURCE, kind)
  const outDir = path.join(OUT, kind)
  await mkdir(outDir, { recursive: true })

  for (const file of (await readdir(dir)).filter((f) => /\.(png|jpe?g)$/i.test(f))) {
    const name = path.parse(file).name
    const input = sharp(path.join(dir, file))
    const { width, height } = await input.metadata()

    const targetWidth = Math.min(width, MAX_WIDTH[kind])
    const targetHeight = Math.round((height / width) * targetWidth)

    await input
      .resize({ width: targetWidth, withoutEnlargement: true })
      .webp({ quality: 82, effort: 5 })
      .toFile(path.join(outDir, `${name}.webp`))

    manifest[`/assets/${kind}/${name}.webp`] = { width: targetWidth, height: targetHeight }
    console.log(`${kind}/${name}.webp  ${targetWidth}x${targetHeight}`)
  }
}

// Intrinsic sizes so every <img> can reserve its space and stop layout shift.
await writeFile(
  path.join(ROOT, 'src/data/imageSizes.js'),
  `// Generated by scripts/optimize-images.mjs - do not edit by hand.\nexport const IMAGE_SIZES = ${JSON.stringify(manifest, null, 2)}\n`,
)
console.log(`\n${Object.keys(manifest).length} images written`)
